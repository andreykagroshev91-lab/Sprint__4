    @Test
    public void checkFAQQuestionAnswer() {
        if ("chrome".equals(browserName)) {
            setupChrome();
        } else {
            setupFirefox();
        }

        MainPage mainPage = new MainPage(driver);

        // Получаем текст вопроса перед кликом
        String actualQuestion = mainPage.getQuestionText(questionIndex);

        // ПРОВЕРЯЕМ ТЕКСТ ВОПРОСА
        Assert.assertEquals("Текст вопроса не соответствует ожидаемому", expectedQuestion, actualQuestion);

        // Нажатие на вопрос
        mainPage.clickQuestion(questionIndex);

        // Получение текста ответа
        String actualAnswer = mainPage.getAnswerText(questionIndex);

        // ПРОВЕРЯЕМ ТЕКСТ ОТВЕТА
        Assert.assertEquals("Текст ответа не соответствует ожидаемому", expectedAnswer, actualAnswer);
    }
